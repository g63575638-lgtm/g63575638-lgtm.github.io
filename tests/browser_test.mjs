import { chromium } from '/usr/local/lib/node_modules_global/playwright/index.mjs';
const shots = process.argv[2] || '/tmp/shots'; import fs from 'fs'; fs.mkdirSync(shots, { recursive: true });
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.type() + ': ' + m.text().slice(0, 1500)); });
p.on('pageerror', e => errors.push('PAGEERROR: ' + e.message + '\n' + (e.stack || '').slice(0, 800)));
await p.addInitScript(() => { window.__FG_TEST = true; });
await p.goto('http://localhost:8765/index.html');
await p.waitForTimeout(2500);
await p.screenshot({ path: shots + '/00_landing.png' });
const t0 = Date.now();
await p.evaluate(() => FG.desktop());
const st = await p.evaluate(() => FG.waitState('menu', 90000));
console.log('state after boot:', st, 'in', Date.now() - t0, 'ms');
await p.waitForTimeout(1500);
await p.screenshot({ path: shots + '/01_menu.png' });
console.log('stats', await p.evaluate(() => JSON.stringify(FG.APP.glx.stats)));
console.log(errors.slice(0, 20).join('\n') || 'no console errors');
await b.close();
